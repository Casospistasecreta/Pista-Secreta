/** Devolve a conversa com as mensagens extras intercaladas por data (as originais nunca são alteradas ou removidas). */
export function withExtras(conversation: Conversation): Conversation {
  const rows = EXTRAS[conversation.id];
  if (!rows) return conversation;
  const extra: Message[] = rows.map(([who, at, text], index) => ({
    id: `x${String(index + 1).padStart(2, "0")}`,
    from: who === "m" ? "victim" : "them",
    at,
    text,
  }));
  const merged = [...conversation.messages, ...extra]
    .map((message, index) => ({ message, index, key: sortKey(message.at) }))
    .sort((a, b) => a.key - b.key || a.index - b.index)
    .map((entry) => entry.message);
  return { ...conversation, messages: merged };
}
